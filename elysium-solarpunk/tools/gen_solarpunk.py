#!/usr/bin/env python3
"""
Build the whole solarpunk set from one table.

    python3 elysium-solarpunk/tools/gen_solarpunk.py

<h2>Why one table</h2>

A decorative block is the same fact written down eight times: a Java
registration, a blockstate, a block model, an item model, a texture, a language
entry, a recipe and a loot table. Miss the loot table and it drops nothing.
Miss the language entry and it is called
``block.elysiumsolarpunk.woven_cane_block``. Miss the item model and it is a
purple cube. None of that fails a build and none of it appears in a log — it is
found by a player, in a world, holding the wrong thing.

Thirty-three blocks is too many to write eight times each and stay honest. So
there is one table, below, and everything else is derived from it — the Java
included. `validate.py` reads the *shipped* files back and compares them
against this table, so a hand-edit to a generated file is caught rather than
silently regenerated away.

<h2>What is hand-written, and why</h2>

Four Java files, all of them behaviour rather than data:

  * ``ElysiumSolarpunk``       — the @Mod entry point.
  * ``item/DescribedBlockItem`` — a block item that says what its block is for.
  * ``block/PendingMachine``    — the marker interface on an unfinished machine.
  * ``block/pending/PendingMachineBlock`` — the shared body of one.

Everything else in ``src`` is generated, and says so at the top of the file.

<h2>The machines</h2>

All eight machines now do what their name says, and ``MACHINES.md`` records
that nothing is outstanding. While any of them was still decoration, three
things had to agree and ``validate.py`` cross-checked them:

  1. their block classes lived in ``block/pending/``, a directory whose name is
     the note;
  2. ``MACHINES.md`` at the module root listed each one and the behaviour it
     still owed;
  3. each class implemented ``PendingMachine`` and returned that same sentence,
     which the block item also showed the player as a tooltip.

That machinery is kept rather than deleted. The empty list is a zero, not an
end: a ninth machine added to ``MACHINES`` gets its stub, its row and its
tooltip back on the next run.

Finishing one means implementing it, moving its class out of ``pending/`` and
deleting its row from the table below. Nothing else has to be remembered.
"""
