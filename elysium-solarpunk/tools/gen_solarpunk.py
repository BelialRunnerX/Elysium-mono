def java_constant(block_id):
    return block_id.upper()


def properties_for(spec, variant, indent=20):
    """The BlockBehaviour.Properties chain for one block, as Java source."""
    if variant == "machine":
        strength = (3.0, 6.0)
        sound = "COPPER"
        light = spec.get("light", 0)
        colour = "COLOR_ORANGE"
        solid = True
        parts = []
    else:
        strength = spec["strength"]
        sound = spec["sound"]
        light = spec.get("light", 0)
        colour = {
            "earth": "DIRT", "plaster": "TERRACOTTA_WHITE", "patina": "WARPED_STEM",
            "brass": "GOLD", "cane": "COLOR_YELLOW", "clay": "TERRACOTTA_ORANGE",
            "copper": "COLOR_ORANGE", "leaf": "PLANT", "bloom": "COLOR_YELLOW",
            "soil": "DIRT", "teal": "COLOR_CYAN",
            # All three whites map to the same colour on purpose: a map is not
            # where a builder tells marble from limestone, and three near-white
            # map colours would only make the map harder to read.
            "marble": "QUARTZ", "limestone": "QUARTZ", "alabaster": "QUARTZ",
            "gold": "GOLD", "iron": "METAL",
        }[spec["tile"][1]]
        solid = spec.get("solid", True)
        parts = []

    parts.append(f".mapColor(MapColor.{colour})")
    parts.append(f".strength({strength[0]}F, {strength[1]}F)")
    parts.append(f".sound(SoundType.{sound})")
    if light:
        parts.append(f".lightLevel(state -> {light})")
    if not solid:
        parts.append(".noOcclusion()")
    pad = "\n" + " " * indent
    return "BlockBehaviour.Properties.of()" + pad + pad.join(parts)


def java_block_line(block_id, spec, variant, base_id):
    name = java_constant(block_id)
    if variant in ("stairs", "machine"):
        # The properties chain is an argument on its own line, so it is indented
        # one step further than a chain that opens the call.
        props = properties_for(spec, variant, indent=28)
    else:
        props = properties_for(spec, variant)

    if variant == "stairs":
        body = (f"new StairBlock({java_constant(base_id)}.get().defaultBlockState(),\n"
                f"                            {props})")
    elif variant == "slab":
        body = f"new SlabBlock({props})"
    elif variant == "wall":
        body = f"new WallBlock({props})"
    elif variant == "machine":
        working = next((w for w in WORKING if w["id"] == block_id), None)
        # A graduated machine names its own class; one still pending names the
        # stub in block/pending/. That single line is the whole structural
        # difference between the two states.
        named = (working["class"].rsplit(".", 1)[1] if working
                 else machine_class(block_id))
        body = (f"new {named}(\n"
                f"                            {props})")
    elif spec.get("block_class") and variant is None:
        # A building block that brought its own behaviour. One line, because the
        # alternative — a second WORKING-shaped table for blocks that are not
        # machines — would be a second place for a block to be declared and a
        # second place for its registration order to drift.
        body = f"new {spec['block_class'].rsplit('.', 1)[1]}({props})"
    else:
        body = f"new Block({props})"
    return (f"    public static final DeferredHolder<Block, Block> {name} =\n"
            f"            BLOCKS.register(\"{block_id}\", () ->\n"
            f"                    {body});\n")


def machine_class(block_id):
    return "".join(part.capitalize() for part in block_id.split("_")) + "Block"


