def main():
    # Only the directories this script owns. The four hand-written Java files
    # are not in any of them, which is the point of the split.
    for stale in (f"assets/{NS}/blockstates", f"assets/{NS}/models",
                  f"assets/{NS}/textures", f"assets/{NS}/lang", "data"):
        shutil.rmtree(RES / stale, ignore_errors=True)

    textures = write_textures()
    write_models()
    write_json(f"assets/{NS}/lang/en_us.json", build_lang())
    recipes = write_recipes()
    processed = write_processing_recipes()
    loot = write_loot()
    tagged = write_tags()
    found = write_worldgen()
    write_content_java()
    write_machine_java()
    write_machines_manifest()

    blocks = all_block_ids()
    print(f"solarpunk: {len(blocks)} blocks ({len(MACHINES)} of them pending), "
          f"{len(INGREDIENTS)} ingredients")
    print(f"           {textures} textures, {recipes} recipes, {loot} loot tables, "
          f"{tagged} tag entries")
    print(f"           {processed} machine recipes across "
          f"{len(processing_recipes())} processing machines")
    print(f"           {found} stone(s) generate in the world")
    print(f"           MACHINES.md lists {len(MACHINES)} machines still owed behaviour")


if __name__ == "__main__":
    main()
