def sprite_briquette(ramp, seed):
    """
    A pressed block of dried algae: a brick with a grain to it.

    Deliberately brick-shaped rather than lumpy. It sits in a furnace's fuel
    slot next to coal and charcoal, and a player scanning a hotbar reads the
    silhouette before the colour — so it wants to look like fuel, and the green
    is what says whose fuel it is.
    """
    tile = Tile()
    for y in range(4, 12):
        for x in range(2, 14):
            # Horizontal grain: the layers it was pressed in.
            level = 3 if (y - 4) % 3 else 2
            level += step(seed, x, y, 40, spread=2)
            tile.put(x, y, ramp[clamp(level)])
    for x in range(2, 14):
        tile.put(x, 4, ramp[4])
        tile.put(x, 11, ramp[1])
    for x in range(1, 15):
        tile.put(x, 3, OUTLINE)
        tile.put(x, 12, OUTLINE)
    for y in range(3, 13):
        tile.put(1, y, OUTLINE)
        tile.put(14, y, OUTLINE)
    # A couple of paler flecks, so it reads as compressed matter rather than a
    # painted rectangle.
    for k in range(5):
        tile.put(3 + noise(seed, k, 0, 41) % 10,
                 5 + noise(seed, k, 1, 41) % 6, ramp[4])
    return tile


def sprite_flakes(ramp, seed):
    """Verdigris: a scatter of patina flakes."""
    tile = Tile()
    for k in range(26):
        x = 3 + noise(seed, k, 0, 20) % 10
        y = 4 + noise(seed, k, 1, 20) % 9
        level = 1 + (k % 4)
        tile.put(x, y, ramp[clamp(level)])
        tile.put(x + 1, y, ramp[clamp(level - 1)])
        tile.put(x, y + 1, ramp[clamp(level - 1)])
    return tile


def sprite_skein(ramp, seed):
    """
    Plant fibre: a loose bundle of strands, tied at the waist.

    Drawn as strands rather than as a shape with texture on it. The first
    version was a rounded blob with noise, and at sixteen pixels that is
    indistinguishable from every other rounded blob with noise in the game — the
    thing that makes fibre read as fibre is that you can count the strands.
    """
    tile = Tile()
    strands = 7
    left = 8 - strands // 2
    for index in range(strands):
        x = left + index
        # Each strand drifts by a pixel or two over its length, so the bundle
        # is not a comb. Same noise source as every other sprite here.
        for y in range(2, 14):
            wander = (noise(seed, index, y // 3, 3) % 3) - 1
            level = 4 - (index % 3)
            if y in (7, 8):
                level = clamp(level - 2)        # the tie, in shadow
                tile.put(x + wander, y, ramp[level])
                continue
            tile.put(x + wander, y, ramp[clamp(level)])
    # The tie itself, across the waist.
    for x in range(left - 1, left + strands + 1):
        tile.put(x, 7, ramp[clamp(0)])
    return tile


def sprite_panel(ramp, seed):
    """
    Woven cane: one small woven square, held in the hand.

    Drawn at a two-pixel pitch with the two directions three ramp steps apart.
    A one-step difference is what the first version used and it read as a plain
    brown square with an outline — at sixteen pixels, subtlety is just absence.
    """
    tile = Tile()
    for y in range(4, 12):
        for x in range(4, 12):
            over = ((x // 2) + (y // 2)) % 2 == 0
            level = 4 if over else 1
            # The trailing edge of each strand, which is what gives the weave
            # its over-and-under rather than a checkerboard.
            if over and y % 2 == 1:
                level -= 1
            if not over and x % 2 == 1:
                level += 1
            tile.put(x, y, ramp[clamp(level)])
    for i in range(3, 13):
        tile.put(i, 3, OUTLINE)
        tile.put(i, 12, OUTLINE)
        tile.put(3, i, OUTLINE)
        tile.put(12, i, OUTLINE)
    return tile


def sprite_ingot(ramp, seed):
    """
    A bar: a top face, a front face, and an outline traced from the silhouette.

    The first version drew the outline as two full-width rows above and below,
    which is not the outline of a trapezoid — it is the outline of a rectangle,
    and the sprite came out as a featureless pill. Tracing the outline from the
    shape itself is both shorter and the only version that stays correct if the
    shape changes.
    """
    tile = Tile()
    # Front face, narrowing toward the bottom; top face sitting on it.
    front = {(x, y) for y in range(8, 12) for x in range(4 + (y - 8), 13 - (y - 8))}
    top = {(x, y) for y in range(5, 8) for x in range(3 + (7 - y), 14 - (7 - y))}
    shape = front | top

    for (x, y) in top:
        level = 4 if y < 7 else 3
        tile.put(x, y, ramp[clamp(level + step(seed, x, y, 22, spread=2))])
    for (x, y) in front:
        level = 2 if y < 10 else 1
        tile.put(x, y, ramp[clamp(level + step(seed, x, y, 23, spread=2))])
    # The lit edge where the two faces meet.
    for x in range(5, 12):
        if (x, 8) in shape:
            tile.put(x, 8, ramp[4])

    for (x, y) in sorted(shape):
        for (dx, dy) in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            if (x + dx, y + dy) not in shape:
                tile.put(x + dx, y + dy, OUTLINE)
    return tile


def sprite_resin(ramp, seed):
    """Bloom resin: a drop with a light in it."""
    tile = Tile()
    for y in range(16):
        for x in range(16):
            dx, dy = x - 7.5, y - 8.5
            dist = (dx * dx + dy * dy * 0.8) ** 0.5
            if dist > 5.0:
                continue
            level = clamp(4 - int(dist * 0.8))
            tile.put(x, y, ramp[level])
    for y in range(16):
        for x in range(16):
            dx, dy = x - 7.5, y - 8.5
            dist = (dx * dx + dy * dy * 0.8) ** 0.5
            if 5.0 <= dist < 6.0:
                tile.put(x, y, OUTLINE)
    tile.put(6, 6, "#ffffff")
    tile.put(7, 6, ramp[4])
    return tile


