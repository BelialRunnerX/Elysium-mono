# --- the pipe shape --------------------------------------------------------
#
# A core and six arms, assembled by a multipart blockstate from two models.
#
# Written out as boxes rather than parented to a vanilla model because nothing
# in vanilla is this shape: a chorus plant is the same idea and its models are
# tuned to a plant's proportions, and a fence post is one arm at a time in the
# wrong places. Two elements, stated once each, is less to be wrong about than
# a parent whose UVs happen to suit something else.
#
# The arm is modelled pointing north, and the blockstate rotates that one model
# to all six faces — the same trick and the same rotations vanilla's chorus
# plant uses, which is why up is x=270 and down is x=90 rather than the other
# way round.

PIPE_CORE = (5, 5, 5, 11, 11, 11)
PIPE_ARM = (6, 6, 0, 10, 10, 5)


def _pipe_faces(texture, box, skip=None):
    """Six faces of a box, each sampling the block's own texture.

    The UV is taken from the box's own extent rather than left to default, so
    an arm samples a strip of the grating rather than the whole tile squeezed
    into a sixth of the space — which is what makes a run of pipe read as one
    continuous thing instead of a row of separately-wrapped stubs.
    """
    x1, y1, z1, x2, y2, z2 = box
    uv = {
        "north": [16 - x2, 16 - y2, 16 - x1, 16 - y1],
        "south": [x1, 16 - y2, x2, 16 - y1],
        "west": [z1, 16 - y2, z2, 16 - y1],
        "east": [16 - z2, 16 - y2, 16 - z1, 16 - y1],
        "up": [x1, z1, x2, z2],
        "down": [x1, 16 - z2, x2, 16 - z1],
    }
    return {face: {"uv": [round(v, 2) for v in coords], "texture": texture}
            for face, coords in uv.items() if face != skip}


def _write_pipe(base, render):
    texture = f"{NS}:block/{base}"
    core = {
        "textures": {"pipe": texture, "particle": texture},
        "elements": [{
            "from": list(PIPE_CORE[:3]), "to": list(PIPE_CORE[3:]),
            "faces": _pipe_faces("#pipe", PIPE_CORE),
        }],
    }
    # The arm's outward face is left off: it is either buried in the neighbour
    # or it is the face of the machine it plugs into, and drawing it is a
    # z-fighting flicker in both cases.
    arm = {
        "textures": {"pipe": texture, "particle": texture},
        "elements": [{
            "from": list(PIPE_ARM[:3]), "to": list(PIPE_ARM[3:]),
            "faces": _pipe_faces("#pipe", PIPE_ARM, skip="north"),
        }],
    }
    # In hand and in the creative tab, a bare core reads as a small cube and
    # tells a player nothing. A straight length of pipe reads as a pipe.
    inventory = {
        "parent": "minecraft:block/block",
        "textures": {"pipe": texture, "particle": texture},
        "display": {
            "gui": {"rotation": [30, 45, 0], "translation": [0, 0, 0],
                    "scale": [0.8, 0.8, 0.8]},
            "fixed": {"rotation": [0, 90, 0], "scale": [1, 1, 1]},
        },
        "elements": [
            {"from": list(PIPE_CORE[:3]), "to": list(PIPE_CORE[3:]),
             "faces": _pipe_faces("#pipe", PIPE_CORE)},
            {"from": [6, 6, 0], "to": [10, 10, 5],
             "faces": _pipe_faces("#pipe", (6, 6, 0, 10, 10, 5), skip="north")},
            {"from": [6, 6, 11], "to": [10, 10, 16],
             "faces": _pipe_faces("#pipe", (6, 6, 11, 10, 10, 16), skip="south")},
        ],
    }
    for model in (core, arm, inventory):
        if render:
            model["render_type"] = f"minecraft:{render}"
    write_json(f"assets/{NS}/models/block/{base}_core.json", core)
    write_json(f"assets/{NS}/models/block/{base}_arm.json", arm)
    write_json(f"assets/{NS}/models/block/{base}.json", inventory)
    write_json(f"assets/{NS}/models/item/{base}.json", {"parent": model_ref(base)})

    arm_ref = model_ref(f"{base}_arm")
    write_json(f"assets/{NS}/blockstates/{base}.json", {
        "multipart": [
            {"apply": {"model": model_ref(f"{base}_core")}},
            {"when": {"north": "true"}, "apply": {"model": arm_ref}},
            {"when": {"east": "true"}, "apply": {"model": arm_ref, "y": 90}},
            {"when": {"south": "true"}, "apply": {"model": arm_ref, "y": 180}},
            {"when": {"west": "true"}, "apply": {"model": arm_ref, "y": 270}},
            {"when": {"up": "true"}, "apply": {"model": arm_ref, "x": 270}},
            {"when": {"down": "true"}, "apply": {"model": arm_ref, "x": 90}},
        ],
    })


def _decorate(model, render):
    if render:
        model["render_type"] = f"minecraft:{render}"
    return model


def _write_stairs(name, faces, render):
    for suffix, parent in (("", "minecraft:block/stairs"),
                           ("_inner", "minecraft:block/inner_stairs"),
                           ("_outer", "minecraft:block/outer_stairs")):
        write_json(f"assets/{NS}/models/block/{name}{suffix}.json",
                   _decorate({"parent": parent, "textures": dict(faces)}, render))
    write_json(f"assets/{NS}/models/item/{name}.json", {"parent": model_ref(name)})

    # The forty rows a stair block needs: four facings, two halves, five
    # shapes.
    #
    # This is vanilla's table, not an invention. Two things in it are easy to
    # get wrong and impossible to notice in a screenshot of a straight run:
    #
    #   * the "left" corners sit a quarter turn back from the "right" ones,
    #     which is what keeps a corner pointing into the bend rather than out
    #     of it;
    #   * on the top half the block is flipped on X, and flipping reverses
    #     handedness — so the quarter turn moves from the left shapes to the
    #     right ones instead of being applied to the same two.
    #
    # Get either backwards and stairs look right until somebody builds a
    # spiral.
    base_y = {"east": 0, "west": 180, "south": 90, "north": 270}
    models = {"straight": model_ref(name),
              "inner_left": model_ref(name + "_inner"),
              "inner_right": model_ref(name + "_inner"),
              "outer_left": model_ref(name + "_outer"),
              "outer_right": model_ref(name + "_outer")}

    variants = {}
    for half in ("bottom", "top"):
        flipped = half == "top"
        for shape, model in models.items():
            turned_back = shape.endswith("_right") if flipped \
                else shape.endswith("_left")
            for facing, y0 in base_y.items():
                y = (y0 + (90 if turned_back else 0)) % 360 if flipped \
                    else (y0 - (90 if turned_back else 0)) % 360
                row = {"model": model}
                if flipped:
                    row["x"] = 180
                if y:
                    row["y"] = y
                if flipped or y:
                    row["uvlock"] = True
                variants[f"facing={facing},half={half},shape={shape}"] = row
    write_json(f"assets/{NS}/blockstates/{name}.json", {"variants": variants})


def _write_slab(name, base, faces, render):
    write_json(f"assets/{NS}/models/block/{name}.json",
               _decorate({"parent": "minecraft:block/slab", "textures": dict(faces)},
                         render))
    write_json(f"assets/{NS}/models/block/{name}_top.json",
               _decorate({"parent": "minecraft:block/slab_top", "textures": dict(faces)},
                         render))
    write_json(f"assets/{NS}/models/item/{name}.json", {"parent": model_ref(name)})
    write_json(f"assets/{NS}/blockstates/{name}.json", {"variants": {
        "type=bottom": {"model": model_ref(name)},
        "type=top": {"model": model_ref(name + "_top")},
        "type=double": {"model": model_ref(base)},
    }})


def _write_wall(name, side, render):
    for suffix, parent in (("_post", "minecraft:block/template_wall_post"),
                           ("_side", "minecraft:block/template_wall_side"),
                           ("_side_tall", "minecraft:block/template_wall_side_tall")):
        write_json(f"assets/{NS}/models/block/{name}{suffix}.json",
                   _decorate({"parent": parent, "textures": {"wall": side}}, render))
    write_json(f"assets/{NS}/models/block/{name}_inventory.json",
               _decorate({"parent": "minecraft:block/wall_inventory",
                          "textures": {"wall": side}}, render))
    write_json(f"assets/{NS}/models/item/{name}.json",
               {"parent": model_ref(name + "_inventory")})

    multipart = [{"when": {"up": "true"}, "apply": {"model": model_ref(name + "_post")}}]
    for facing, turn in (("north", 0), ("east", 90), ("south", 180), ("west", 270)):
        for height, suffix in (("low", "_side"), ("tall", "_side_tall")):
            apply = {"model": model_ref(name + suffix), "uvlock": True}
            if turn:
                apply["y"] = turn
            multipart.append({"when": {facing: height}, "apply": apply})
    write_json(f"assets/{NS}/blockstates/{name}.json", {"multipart": multipart})


