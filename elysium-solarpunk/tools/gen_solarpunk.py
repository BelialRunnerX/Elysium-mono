def tile_machine_top(ramp, seed):
    """A machine seen from above: a panel with a round hatch."""
    tile = tile_plate(ramp, seed)
    for y in range(16):
        for x in range(16):
            dx, dy = x - 7.5, y - 7.5
            dist = (dx * dx + dy * dy) ** 0.5
            if dist < 3.2:
                tile.put(x, y, ramp[clamp(1 + int(dist))])
            elif dist < 4.2:
                tile.put(x, y, ramp[0])
    return tile


def tile_machine_front(ramp, glow, seed):
    """
    The working face: a window, a vent and a dial.

    This is the one texture that has to carry the whole claim that these are
    machines, because everything behind it is a cube. The window colour is what
    separates a bioreactor from a kiln.
    """
    tile = tile_plate(ramp, seed)
    # Window
    for y in range(3, 10):
        for x in range(3, 13):
            edge = x in (3, 12) or y in (3, 9)
            if edge:
                tile.put(x, y, ramp[0])
            else:
                # Fully opaque. A machine is a solid block, and the solid
                # renderer does not blend — alpha below 255 here is drawn as
                # though it were 255 anyway, so writing it is a lie about what
                # the texture does.
                level = 2 + (noise(seed, x, y, 17) % 3)
                tile.put(x, y, glow[clamp(level)])
    # Vent slots along the bottom
    for slot in range(3):
        x0 = 3 + slot * 4
        for x in range(x0, x0 + 3):
            tile.put(x, 12, ramp[0])
            tile.put(x, 13, ramp[1])
    # A dial in the bottom-right corner
    tile.put(13, 12, ramp[4])
    tile.put(14, 12, ramp[3])
    tile.put(13, 13, ramp[3])
    tile.put(14, 13, glow[4])
    return tile


