def seed_of(name):
    value = 7
    for character in name:
        value = (value * 131 + ord(character)) & 0xFFFFFFFF
    return value


def write_textures():
    written = 0
    block_dir = RES / f"assets/{NS}/textures/block"
    item_dir = RES / f"assets/{NS}/textures/item"

    for entry in INGREDIENTS:
        kind, palette = entry["sprite"]
        SPRITES[kind](PALETTE[palette], seed_of(entry["id"])).save(
            item_dir / f"{entry['id']}.png")
        written += 1

    for entry in BUILDING:
        kind, palette = entry["tile"]
        # The seed is the *base* block's, not this block's, so every trim
        # variant of a stone sits on an identical face and only the metal
        # differs. Seeding each one separately would give eight subtly
        # different marbles that a builder cannot mix in one wall.
        seed = seed_of(entry.get("base", entry["id"]))
        tile = TILES[kind](PALETTE[palette], seed)
        if entry.get("polish"):
            tile = polish(tile, PALETTE[palette], seed)
        if "overlay" in entry:
            pattern, metal = entry["overlay"]
            tile = OVERLAYS[pattern](tile, PALETTE[metal], seed_of(entry["id"]))
        tile.save(block_dir / f"{entry['id']}.png")
        written += 1
        if "top" in entry:
            kind, palette = entry["top"]
            TILES[kind](PALETTE[palette], seed_of(entry["id"] + "_top")).save(
                block_dir / f"{entry['id']}_top.png")
            written += 1

    for entry in ALL_MACHINES:
        seed = seed_of(entry["id"])
        glow = PALETTE[entry["glow"]]
        tile_plate(PALETTE["brass"], seed).save(block_dir / f"{entry['id']}_side.png")
        tile_machine_top(PALETTE["brass"], seed).save(
            block_dir / f"{entry['id']}_top.png")
        tile_machine_front(PALETTE["brass"], glow, seed).save(
            block_dir / f"{entry['id']}_front.png")
        written += 3

    return written


