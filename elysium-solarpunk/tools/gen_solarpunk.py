def write_tags():
    mineable = {"pickaxe": [], "axe": []}
    stairs, slabs, walls = [], [], []

    for block_id, _, spec, variant in block_entries():
        tool = "pickaxe" if variant == "machine" else spec.get("tool")
        if tool in mineable:
            mineable[tool].append(f"{NS}:{block_id}")
        if variant == "stairs":
            stairs.append(f"{NS}:{block_id}")
        elif variant == "slab":
            slabs.append(f"{NS}:{block_id}")
        elif variant == "wall":
            walls.append(f"{NS}:{block_id}")

    for tool, values in mineable.items():
        write_json(f"data/minecraft/tags/block/mineable/{tool}.json",
                   {"replace": False, "values": values})
    # #minecraft:walls is not decoration: WallBlock reads it to decide what to
    # connect to, so a wall left out of it stands alone next to its own kind.
    write_json("data/minecraft/tags/block/walls.json",
               {"replace": False, "values": walls})
    write_json("data/minecraft/tags/block/stairs.json",
               {"replace": False, "values": stairs})
    write_json("data/minecraft/tags/block/slabs.json",
               {"replace": False, "values": slabs})

    # No vanilla item tag holds the mushroom blocks, so this mod ships one.
    # Its own namespace, because a mod writing into #minecraft: a tag vanilla
    # does not define is a mod inventing vanilla content.
    write_json(f"data/{NS}/tags/item/pressable_fungus.json",
               {"replace": False, "values": [
                   "minecraft:brown_mushroom_block",
                   "minecraft:red_mushroom_block",
                   "minecraft:mushroom_stem",
               ]})

    # The kiln's input set, as data rather than as a switch statement in Java.
    # A pack can widen it without touching the mod, which is the whole reason
    # the kiln asks a tag instead of asking for a list of items it knows about.
    write_json(f"data/{NS}/tags/item/kiln_inputs.json",
               {"replace": False, "values": kiln_inputs()})

    return (len(stairs) + len(slabs) + len(walls)
            + sum(len(v) for v in mineable.values()) + len(kiln_inputs()))


