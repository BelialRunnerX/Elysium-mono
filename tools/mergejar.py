#!/usr/bin/env python3
"""
Merge the six Elysium mod jars into one installable jar.

    python3 tools/mergejar.py dist/elysium-all-1.0.0.jar dist/elysiumlib-1.0.0.jar ...

NeoForge reads every `[[mods]]` block in `META-INF/neoforge.mods.toml` and finds
each mod's `@Mod` class by scanning the jar, so one file can carry any number of
mods. That is what this produces: one jar, six mods, every mod id unchanged.

Mod ids are deliberately left alone. Renaming them would rename every registry
entry, attachment, lang key, texture path, recipe and loot table with them, and
every existing world would lose its Elysium items, blocks, standing and claims.
It would also dissolve the rule the whole repository is built on — the library
must not know what is built on top of it — for no gain: a jar is the unit a
player installs, and a mod id is not.

<h2>The part that is not just concatenation</h2>

Six jars loaded separately are six resource packs, and Minecraft merges data
packs. One jar is one pack, and a path can only hold one file. So any two
modules that ship the *same path* are a silent loss of whatever the loser said:
today that is `data/minecraft/tags/block/mineable/pickaxe.json`, written by both
elysium-core and elysium-dungeons.

Getting that wrong is not a crash. It is nine Elysium blocks that quietly stop
dropping anything when mined, or a Rift Frame that does — discovered by a player
weeks later and nearly impossible to trace back to a packaging step.

So collisions are not resolved by last-writer-wins. They are:

  * **unioned**, for additive tag files (`replace: false`), which is exactly
    what the game itself would have computed from two packs; or
  * **expected**, for the one file this tool is replacing anyway; or
  * **fatal**.

That last case is the important one. A new collision means somebody added a file
whose merge semantics this tool has not been taught, and the correct response is
to stop and say so rather than to guess.
"""
import argparse
import json
import os
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import modstoml

MODS_TOML = "META-INF/neoforge.mods.toml"
MANIFEST = "META-INF/MANIFEST.MF"

ISSUE_TRACKER = "https://github.com/BelialRunnerX/Elysium-mono/issues"

BANNER = """\
Elysium — all six mods in one jar.

GENERATED by tools/mergejar.py. Do not edit: the next merge overwrites it.
Each block below is carried across verbatim from the module named above it, so
the reasons recorded in those files survive the merge.

The six mods keep their own ids. A merged jar changes how Elysium is installed
and nothing about what it registers, so existing worlds are unaffected."""


class Collision(Exception):
    pass


def is_additive_tag(path):
    """
    A data-pack tag file, which two packs are expected to both contribute to.

    Matched on the path shape rather than on the contents, so that a tag file
    which is *missing* its "replace" key — the default is false, so it is still
    additive — is still recognised.
    """
    return (path.startswith("data/")
            and "/tags/" in path
            and path.endswith(".json"))


def union_tags(path, payloads):
    """
    Merge additive tag files the way a data pack stack would.

    Refuses on `replace: true`, which means "discard what earlier packs said"
    and has no order-independent answer once the packs are one pack. Nothing in
    this repository uses it; if something starts to, this should be read again
    rather than extended by reflex.
    """
    values = []
    for module, raw in payloads:
        parsed = json.loads(raw)
        if parsed.get("replace"):
            raise Collision(
                f"{path}: {module} sets \"replace\": true. Two packs merged into "
                f"one cannot express that — whichever file wins, the result "
                f"depends on an order that no longer exists.")
        for value in parsed.get("values", []):
            if value not in values:
                values.append(value)
    merged = {"replace": False, "values": values}
    return (json.dumps(merged, indent=2) + "\n").encode("utf-8")


def read_jar(path):
    """Every entry of a jar as {name: bytes}, directories dropped."""
    entries = {}
    with zipfile.ZipFile(path) as archive:
        for info in archive.infolist():
            if info.is_dir():
                continue
            entries[info.filename] = archive.read(info)
    return entries


def order(jar):
    """
    Sort key: the library first, then alphabetically.

    The loader does not care — load order comes from the dependency stanzas in
    the merged toml, not from position in the file. Determinism does. This tool
    is called from two places, `compile.sh` (dependency order) and the Gradle
    `mergeJar` task (whatever `ls` hands it), and without a key of its own the
    same six jars produce two different merged jars: same contents, different
    block order, different bytes. Reproducible output is worth four lines, and
    putting the engine before the five things built on it is how a reader would
    have ordered it anyway.
    """
    name = os.path.basename(jar)
    return (0 if "elysiumlib" in name else 1, name)


def merge(jars, out_path, quiet=False):
    modules = []          # [(display name, {entry: bytes})]
    for jar in sorted(jars, key=order):
        name = os.path.basename(jar)
        modules.append((name, read_jar(jar)))

    # ---- collisions ---------------------------------------------------
    owners = {}
    for name, entries in modules:
        for entry in entries:
            owners.setdefault(entry, []).append(name)

    resolved = {}
    problems = []
    for entry, who in sorted(owners.items()):
        if len(who) == 1:
            continue
        if entry in (MODS_TOML, MANIFEST):
            continue                      # regenerated below
        payloads = [(name, dict(entries)[entry])
                    for name, entries in modules if entry in entries]
        identical = len({payload for _, payload in payloads}) == 1
        if identical:
            continue                      # same bytes; nothing is lost
        if is_additive_tag(entry):
            try:
                resolved[entry] = union_tags(entry, payloads)
            except Collision as problem:
                problems.append(str(problem))
            continue
        if entry.endswith(".class"):
            problems.append(
                f"{entry}: the same class is in {who}. Two modules shipping "
                f"different bytes for one class name cannot both be right, and "
                f"in one jar only one of them exists.")
            continue
        problems.append(
            f"{entry}: shipped with different contents by {who}, and this tool "
            f"has no merge rule for it. Loaded as six jars these were six packs "
            f"and the game merged them; in one jar one silently wins. Teach "
            f"mergejar.py how to merge this file, or move it.")

    if problems:
        print(f"{len(problems)} unmergeable collision(s):\n", file=sys.stderr)
        for problem in problems:
            print("  - " + problem + "\n", file=sys.stderr)
        return 1

    # ---- the merged mods.toml -----------------------------------------
    sources = []
    for name, entries in modules:
        if MODS_TOML not in entries:
            print(f"{name} has no {MODS_TOML} — it is not a mod jar",
                  file=sys.stderr)
            return 1
        sources.append((name, entries[MODS_TOML].decode("utf-8")))

    try:
        merged_toml = modstoml.combine(sources, ISSUE_TRACKER, banner=BANNER)
    except ValueError as problem:
        print(f"cannot merge {MODS_TOML}: {problem}", file=sys.stderr)
        return 1

    mod_ids = modstoml.declared_mod_ids(merged_toml)
    if len(mod_ids) != len(modules):
        print(f"merged mods.toml declares {len(mod_ids)} mods "
              f"({mod_ids}) but {len(modules)} jars went in", file=sys.stderr)
        return 1

    # ---- write ---------------------------------------------------------
    os.makedirs(os.path.dirname(os.path.abspath(out_path)) or ".", exist_ok=True)
    written = 0
    with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED) as out:
        out.writestr(MANIFEST,
                     "Manifest-Version: 1.0\n"
                     "Implementation-Title: Elysium\n"
                     f"Implementation-Version: {version_of(sources)}\n")
        out.writestr(MODS_TOML, merged_toml)
        written += 2

        seen = {MANIFEST, MODS_TOML}
        for name, entries in modules:
            for entry in sorted(entries):
                if entry in seen:
                    continue
                if entry in resolved:
                    out.writestr(entry, resolved[entry])
                else:
                    out.writestr(entry, entries[entry])
                seen.add(entry)
                written += 1

    if not quiet:
        classes = sum(1 for n in seen if n.endswith(".class"))
        size = os.path.getsize(out_path)
        print(f"merged {len(modules)} jars into {out_path}")
        print(f"  {len(mod_ids)} mods: {', '.join(mod_ids)}")
        print(f"  {written} entries ({classes} classes), "
              f"{size / 1024.0:.0f} KiB")
        if resolved:
            for entry in sorted(resolved):
                count = len(json.loads(resolved[entry])["values"])
                print(f"  unioned {entry} -> {count} values")
    return 0


def version_of(sources):
    """The library's version, which the others track."""
    for name, text in sources:
        if "elysiumlib" in name:
            for line in text.splitlines():
                if line.strip().startswith("version="):
                    return line.split("=", 1)[1].strip().strip('"')
    return "0.0.0"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", help="the merged jar to write")
    parser.add_argument("jars", nargs="+",
                        help="the module jars, in any order — see order()")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()

    missing = [jar for jar in args.jars if not os.path.isfile(jar)]
    if missing:
        print(f"no such jar(s): {missing}", file=sys.stderr)
        return 1
    return merge(args.jars, args.output, quiet=args.quiet)


if __name__ == "__main__":
    sys.exit(main())
