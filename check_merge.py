#!/usr/bin/env python3
"""
Can these six modules still be merged into one jar?

    python3 check_merge.py

Run as part of the root validator, before anything is built.

<h2>What this is protecting</h2>

The six mods ship as six jars and also as one. As six jars they are six resource
packs, and Minecraft merges data packs across packs — two mods can both write
`data/minecraft/tags/block/mineable/pickaxe.json` and the game takes the union.
As one jar they are one pack, and a path holds exactly one file.

So every resource path that more than one module ships is a place where the
merged jar can quietly lose something. `tools/mergejar.py` handles the case it
knows about (additive tag files, unioned) and refuses the rest — but that
refusal happens at packaging time, which on a machine that cannot reach the
NeoForge repositories is a long way from the edit that caused it.

This is the same question asked at source level, in under a second, by a
validator that runs before the build. Adding a colliding file should be caught
by the person who added it.

<h2>What counts as a problem</h2>

  * Identical bytes in two modules: fine. Nothing is lost either way.
  * An additive tag file: fine. The merge unions it, which is what the game
    would have done.
  * `META-INF/neoforge.mods.toml`: expected. The merge regenerates it.
  * Anything else: a problem, and the message says which two modules and what
    the choice is.
"""
import json
import os
import re
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent

MODULES = ["elysium-lib", "elysium-core", "elysium-dungeons", "elysium-mobs",
           "elysium-npcs", "elysium-trinkets", "elysium-solarpunk",
           "elysium-armory", "elysium-ascendancy", "elysium-enchanting",
           "elysium-spawners",
           "elysium-space", "elysium-ores", "elysium-flora", "elysium-colonies"]

# Regenerated by the merge, so a collision here is the design.
REGENERATED = {"META-INF/neoforge.mods.toml", "META-INF/MANIFEST.MF"}


# The one additive list in the game's data that is not a tag: NeoForge's
# global loot modifier list has a tag's shape under a different key, and two
# mods both adding a modifier is the normal case rather than a mistake.
GLOBAL_LOOT_MODIFIERS = "data/neoforge/loot_modifiers/global_loot_modifiers.json"


def is_additive_tag(path):
    return (path.startswith("data/") and "/tags/" in path
            and path.endswith(".json")) or path == GLOBAL_LOOT_MODIFIERS


def list_key(path):
    """What the file calls its list. Tags say "values"; loot modifiers say "entries"."""
    return "entries" if path == GLOBAL_LOOT_MODIFIERS else "values"


def main():
    owners = {}
    for module in MODULES:
        root = HERE / module / "src/main/resources"
        if not root.is_dir():
            print(f"  {module} has no src/main/resources")
            continue
        for dirpath, _, filenames in os.walk(root):
            for filename in filenames:
                full = pathlib.Path(dirpath) / filename
                rel = str(full.relative_to(root)).replace(os.sep, "/")
                owners.setdefault(rel, []).append((module, full))

    problems = []
    unioned = []
    for rel, entries in sorted(owners.items()):
        if len(entries) == 1 or rel in REGENERATED:
            continue

        payloads = {full.read_bytes() for _, full in entries}
        if len(payloads) == 1:
            continue                      # identical; nothing can be lost

        who = [module for module, _ in entries]
        if is_additive_tag(rel):
            replacing = [module for module, full in entries
                         if json.loads(full.read_text(encoding="utf-8")).get("replace")]
            if replacing:
                problems.append(
                    f'{rel}: {replacing} set "replace": true. Merged into one '
                    f'pack there is no order left for that to be relative to, '
                    f'so the merge cannot union it.')
            else:
                total = set()
                for _, full in entries:
                    for value in json.loads(
                            full.read_text(encoding="utf-8")).get(list_key(rel), []):
                        total.add(value if isinstance(value, str) else value.get("id"))
                unioned.append((rel, who, len(total)))
            continue

        problems.append(
            f"{rel}: shipped with different contents by {who}. As six jars the "
            f"game merges these; in one jar one of them silently wins. Either "
            f"move the file into one module, or teach tools/mergejar.py how to "
            f"merge it.")

    # ---- the mod list: an emblem and credits on every block (POLISH.md P2) ----
    # A mod list of twenty-nine blank squares and twenty-nine display names is a
    # pack that looks unfinished before a world is loaded. Every manifest names
    # the one generated emblem and credits from its properties; the emblem is in
    # the library jar, 256 square, and drawn only in the interface palette so a
    # palette change redraws it rather than leaving it a different violet.
    emblem = HERE / "elysium-lib/src/main/resources/elysium_logo.png"
    if not emblem.is_file():
        problems.append("the pack has no emblem: tools/gen_emblem.py writes elysium_logo.png "
                        "into the library's resources, and every mod list square is blank without it")
    else:
        try:
            import sys as _sys
            _sys.path.insert(0, str(HERE / "elysium-lib" / "ui"))
            import palette as _palette
            from PIL import Image as _Image
            with _Image.open(emblem) as _img:
                _px = _img.convert("RGBA")
                if _px.size != (256, 256):
                    problems.append(f"the emblem is {_px.size[0]}x{_px.size[1]}, not the 256 square the mod list expects")
                _allowed = {(v >> 16 & 255, v >> 8 & 255, v & 255) for v in _palette.PALETTE.values()}
                _off = {(r, g, b) for (r, g, b, a) in _px.getdata() if a}
                _off -= _allowed
                if _off:
                    problems.append(f"the emblem uses {len(_off)} colour(s) outside the interface palette, "
                                    f"so a palette change would leave it a different violet from the screens")
        except ImportError:
            pass
    for module in sorted(os.listdir(HERE)):
        manifest = HERE / module / "src/main/resources/META-INF/neoforge.mods.toml"
        if not module.startswith("elysium-") or not manifest.is_file():
            continue
        text = manifest.read_text(encoding="utf-8")
        if 'logoFile="elysium_logo.png"' not in text or "logoBlur=false" not in text:
            problems.append(f"{module}: its manifest names no emblem, so its square in the mod list is blank")
        if 'credits="${mod_credits}"' not in text:
            problems.append(f"{module}: its manifest carries no credits")
        props = (HERE / module / "gradle.properties").read_text(encoding="utf-8")
        if not re.search(r"^mod_credits=\S.+$", props, re.M):
            problems.append(f"{module}: gradle.properties defines no mod_credits, which the manifest expands")

    if problems:
        print(f"{len(problems)} PROBLEM(S):")
        for problem in problems:
            print("  - " + problem)
        return 1

    for rel, who, count in unioned:
        print(f"  unioned by the merge: {rel}")
        print(f"    {' + '.join(who)} -> {count} values")
    print(f"mergeable          : {len(owners)} resource paths across "
          f"{len(MODULES)} modules, {len(unioned)} unioned, 0 unmergeable; an emblem and credits on every manifest")
    return 0


if __name__ == "__main__":
    sys.exit(main())
